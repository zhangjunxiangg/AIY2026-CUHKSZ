#!/bin/sh
# Patched copy of /data/gemini335/start-gemini335.sh (original kept on the
# board as start-gemini335.sh.orig). Only change: when the board has no
# wlan0 IPv4 address, fall back to loopback standalone mode instead of
# aborting, so the camera works with only the USB/HDC link attached.
set -eu

BASE=/data/gemini335
RUNTIME="$BASE/runtime"
ENV_FILE="$BASE/gemini335.env"
CONTAINER=rk3588s-gemini335
IMAGE=rk3588s-gemini335-driver:fw-1.4.60-sdk-2.2.8

detect_wlan_ip() {
    output=$(ip -4 addr show wlan0 2>/dev/null || true)
    previous=""
    for word in $output; do
        if [ "$previous" = "inet" ]; then
            printf '%s\n' "${word%/*}"
            return 0
        fi
        previous=$word
    done
    return 1
}

board_ip=$(detect_wlan_ip || true)
if [ -z "$board_ip" ]; then
    echo "WARN: no wlan0 IPv4; falling back to loopback standalone mode" >&2
    board_ip=127.0.0.1
fi

GEMINI_ROS_IP="$board_ip"
GEMINI_ROS_MASTER_URI="http://$board_ip:11311"
GEMINI_START_LOCAL_ROSCORE=1

if [ -f "$ENV_FILE" ]; then
    # This file is generated by configure-car-ros.sh and contains only validated values.
    . "$ENV_FILE"
fi

test -f "$RUNTIME/container-entrypoint.sh"
test -f "$RUNTIME/create-usb-nodes.sh"
test -f "$RUNTIME/capture_gemini335_rgbd.py"
test -f "$RUNTIME/publish_compressed_color.py"

if [ -e /sys/bus/usb/devices/6-1/power/control ]; then
    echo on > /sys/bus/usb/devices/6-1/power/control
fi

docker rm -f "$CONTAINER" >/dev/null 2>&1 || true
# Give the USB video endpoints time to leave the previous driver process.
# Recreating the container immediately can leave ROS nodes registered but
# produce no frames until the container is restarted.
sleep 5
docker create \
    --name "$CONTAINER" \
    --restart unless-stopped \
    --network host \
    --log-driver json-file \
    --log-opt max-size=10m \
    --log-opt max-file=2 \
    --device-cgroup-rule 'c 189:* rmw' \
    -e "ROS_MASTER_URI=$GEMINI_ROS_MASTER_URI" \
    -e "ROS_IP=$GEMINI_ROS_IP" \
    -e "GEMINI_START_LOCAL_ROSCORE=$GEMINI_START_LOCAL_ROSCORE" \
    --entrypoint bash \
    "$IMAGE" /tmp/container-entrypoint.sh >/dev/null

docker cp "$RUNTIME/container-entrypoint.sh" "$CONTAINER:/tmp/container-entrypoint.sh"
docker cp "$RUNTIME/create-usb-nodes.sh" "$CONTAINER:/tmp/create-usb-nodes.sh"
docker cp "$RUNTIME/capture_gemini335_rgbd.py" "$CONTAINER:/tmp/capture_gemini335_rgbd.py"
docker cp "$RUNTIME/publish_compressed_color.py" "$CONTAINER:/tmp/publish_compressed_color.py"
# Web streamer is optional; when present it is started by the entrypoint.
if [ -f /data/gemini335-web/gemini_web_stream.py ]; then
    docker cp /data/gemini335-web/gemini_web_stream.py "$CONTAINER:/tmp/gemini_web_stream.py"
fi
docker start "$CONTAINER" >/dev/null

camera_ready() {
    docker exec "$CONTAINER" bash -lc '
        source /opt/ros/noetic/setup.bash
        timeout 20 rostopic echo -n 1 /aux_camera/depth/image_raw >/dev/null 2>&1
    '
}

# Verify an actual frame rather than only checking that ROS topics exist.
# One automatic restart handles a stale USB endpoint after redeployment.
sleep 8
if ! camera_ready; then
    echo "WARN: no Gemini depth frame after initial start; restarting container once" >&2
    docker restart "$CONTAINER" >/dev/null
    sleep 8
    if ! camera_ready; then
        echo "ERROR: Gemini ROS node is running but no depth frame was received" >&2
        exit 1
    fi
fi

echo "container=$CONTAINER"
echo "ROS_MASTER_URI=$GEMINI_ROS_MASTER_URI"
echo "ROS_IP=$GEMINI_ROS_IP"
echo "local_roscore=$GEMINI_START_LOCAL_ROSCORE"
echo "camera_frame_check=PASS"
